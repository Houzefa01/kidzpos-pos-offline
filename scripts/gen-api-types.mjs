#!/usr/bin/env node
/**
 * gen-api-types.mjs — Génère src/lib/api-types.ts depuis la spec OpenAPI.
 *
 * Deux modes :
 *   • Par défaut : lit le snapshot committé api/openapi.json (déterministe, CI-friendly).
 *   • Avec --from-backend : fetch /v3/api-docs sur le backend en cours d'exécution
 *     (par défaut http://localhost:8080) puis met à jour le snapshot ET re-génère.
 *
 * Workflow attendu :
 *   1. Modification d'un controller / DTO côté backend.
 *   2. Backend en route → `npm run gen:api-types -- --from-backend` régénère le snapshot.
 *   3. Diff sur api/openapi.json visible en review → confirme l'intention du contrat.
 *   4. src/lib/api-types.ts est régénéré en miroir.
 *
 * En CI, on lance juste `npm run gen:api-types` (lit le snapshot committé) et on
 * vérifie via `git diff --exit-code src/lib/api-types.ts` que personne n'a oublié
 * de re-générer après modif backend.
 */

import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SNAPSHOT_PATH = resolve(ROOT, "api/openapi.json");
const OUTPUT_PATH = resolve(ROOT, "src/lib/api-types.ts");
const DEFAULT_BACKEND_URL = process.env.KIDZPOS_API_URL ?? "http://localhost:8080";

async function fetchFromBackend(baseUrl) {
  const url = `${baseUrl.replace(/\/$/, "")}/v3/api-docs`;
  process.stdout.write(`Fetching OpenAPI spec from ${url} … `);
  const res = await fetch(url);
  if (!res.ok) {
    throw new Error(`Backend returned HTTP ${res.status} for ${url}`);
  }
  const json = await res.json();
  process.stdout.write("OK\n");
  return json;
}

async function readSnapshot() {
  const raw = await readFile(SNAPSHOT_PATH, "utf8");
  return JSON.parse(raw);
}

async function writeSnapshot(spec) {
  await mkdir(dirname(SNAPSHOT_PATH), { recursive: true });
  // Tri stable pour des diffs lisibles
  const sorted = JSON.stringify(spec, Object.keys(spec).sort(), 2);
  await writeFile(SNAPSHOT_PATH, sorted + "\n", "utf8");
  console.log(`Snapshot updated: ${SNAPSHOT_PATH}`);
}

async function generateTypes(spec) {
  // openapi-typescript v7 renvoie un AST → astToString pour le code TS final.
  const ast = await openapiTS(spec, {
    // Tous les champs sont marqués `T | undefined` par défaut côté output ;
    // on garde ce comportement car le backend ne marque pas systématiquement
    // les champs nullable (limite Jackson connue → c'est précisément pourquoi
    // on garde Zod en parallèle pour la validation runtime).
    alphabetize: true,
    emptyObjectsUnknown: true,
  });
  const header = [
    "// AUTOGENERATED FILE — DO NOT EDIT MANUALLY.",
    "// Source : api/openapi.json (snapshot du backend).",
    "// Régénérer via : `npm run gen:api-types` (snapshot) ou",
    "// `npm run gen:api-types -- --from-backend` (live, met à jour le snapshot).",
    "//",
    "// Couple avec Zod (src/lib/schemas.ts) : les types ici donnent la complétion",
    "// IDE + le typecheck statique ; Zod attrape les payloads malformés au runtime.",
    "",
  ].join("\n");
  await writeFile(OUTPUT_PATH, header + astToString(ast), "utf8");
  console.log(`Types written : ${OUTPUT_PATH}`);
}

const args = process.argv.slice(2);
const fromBackend = args.includes("--from-backend");
const urlArgIdx = args.indexOf("--url");
const backendUrl = urlArgIdx >= 0 ? args[urlArgIdx + 1] : DEFAULT_BACKEND_URL;

try {
  let spec;
  if (fromBackend) {
    spec = await fetchFromBackend(backendUrl);
    await writeSnapshot(spec);
  } else {
    spec = await readSnapshot();
    console.log(`Using snapshot: ${SNAPSHOT_PATH}`);
  }
  await generateTypes(spec);
  console.log("Done.");
} catch (err) {
  console.error("FAILED:", err.message);
  if (!fromBackend) {
    console.error("Hint: si api/openapi.json est manquant, lancer le backend puis :");
    console.error("      npm run gen:api-types -- --from-backend");
  }
  process.exit(1);
}
